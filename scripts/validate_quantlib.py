"""Write the QuantLib validation tables to ``docs/validation.md``.

Usage (from the repository root): ``python scripts/validate_quantlib.py``
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

import QuantLib as ql

from credit_pricer.data import load_discount_curve
from credit_pricer.validation import (
    VALIDATION_METHODS,
    VALIDATION_SPREADS_BP,
    VALIDATION_TENORS,
    BootstrapRow,
    ComparisonRow,
    run_validation,
)

OUT = Path(__file__).resolve().parents[1] / "docs" / "validation.md"

ENGINES = {
    "isda": "`IsdaCdsEngine` (NoBias, Taylor, Piecewise)",
    "isda_halfday": "`IsdaCdsEngine` (HalfDayBias, Taylor, Piecewise)",
    "midpoint": "`MidPointCdsEngine`",
}


def summary_table(rows: list[ComparisonRow]) -> list[str]:
    out = [
        "| our method | QuantLib engine | cases | max abs diff par spread (bp) "
        "| max abs diff value (bp) | max abs diff RPV01 |",
        "|---|---|---:|---:|---:|---:|",
    ]
    by: dict[str, list[ComparisonRow]] = defaultdict(list)
    for r in rows:
        by[r.method].append(r)
    for m in VALIDATION_METHODS:
        rs = by[m]
        out.append(
            f"| `{m}` | {ENGINES[m]} | {len(rs)} "
            f"| {max(abs(r.d_par_spread_bp) for r in rs):.1e} "
            f"| {max(abs(r.d_upfront_bp) for r in rs):.1e} "
            f"| {max(abs(r.d_rpv01) for r in rs):.1e} |"
        )
    return out


def detail_table(rows: list[ComparisonRow], method: str) -> list[str]:
    out = [
        "| spread level (bp) | maturity | par spread (bp) | diff (bp) | value (bp) "
        "| diff (bp) | RPV01 | diff |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        if r.method == method:
            out.append(
                f"| {r.spread_bp:.0f} | {r.tenor}y | {r.par_spread_bp:.4f} "
                f"| {r.d_par_spread_bp:+.1e} | {r.upfront_bp:.4f} | {r.d_upfront_bp:+.1e} "
                f"| {r.rpv01:.6f} | {r.d_rpv01:+.1e} |"
            )
    return out


def bootstrap_table(rows: list[BootstrapRow]) -> list[str]:
    out = [
        "| spread level (bp) | maturity | survival Q(T) | diff Q(T) | diff value (bp) |",
        "|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        out.append(
            f"| {r.spread_bp:.0f} | {r.tenor}y | {r.survival:.8f} | {r.d_survival:+.1e} "
            f"| {r.d_upfront_bp:+.1e} |"
        )
    return out


def main() -> None:
    discount = load_discount_curve()
    engine_rows, boot_rows = run_validation(discount)
    lines = [
        "# Validation against QuantLib",
        "",
        "Generated by `scripts/validate_quantlib.py` with QuantLib "
        f"{ql.__version__}. Differences are ours minus QuantLib's, per unit notional "
        "expressed in basis points. Value = PV at the trade date for the protection buyer "
        "(including the accrual rebate), i.e. QuantLib's `NPV()`; the quoted upfront is this "
        "value forwarded to cash settlement.",
        "",
        "Grid: flat par spread curves at "
        + ", ".join(f"{s:.0f}" for s in VALIDATION_SPREADS_BP)
        + " bp (bootstrapped at "
        + ", ".join(f"{t}y" for t in VALIDATION_TENORS)
        + "), standard CDS with a 100 bp coupon, recovery 40%, synthetic discount curve, "
        "trade date 2026-11-05.",
        "",
        "## Engine level (identical curves in both libraries)",
        "",
        *summary_table(engine_rows),
        "",
        "## Bootstrap level (each library bootstraps its own hazard curve)",
        "",
        "QuantLib: `SpreadCdsHelper` (ISDA model) + `PiecewiseFlatHazardRate`. "
        "Ours: `bootstrap_survival_curve(..., method=\"isda_halfday\")`, because "
        "QuantLib's helper prices with the half-day accrual bias.",
        "",
        *bootstrap_table(boot_rows),
    ]
    for m in VALIDATION_METHODS:
        lines += ["", f"## Detail: `{m}` vs {ENGINES[m]}", "", *detail_table(engine_rows, m)]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(summary_table(engine_rows)))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
