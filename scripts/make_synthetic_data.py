"""Generate the SYNTHETIC data sets in ``data/`` (deterministic, seeded).

Nothing here is market data. Levels are chosen to look plausible for illustration:

* rates: an OIS-style deposit/swap curve with a gently inverted front end;
* single names: three stylised issuers (low/mid investment grade, high yield);
* index: 125 names with log-normally dispersed spreads and an upward-sloping term
  structure; index quotes = intrinsic spread + a chosen negative basis;
* tranches: upfront quotes on the 5y index pool generated from a chosen base
  correlation skew (stored alongside the quotes for the round-trip check).

Run from the repository root: ``python scripts/make_synthetic_data.py``.
"""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np

from credit_pricer.data import VALUATION_DATE, load_discount_curve
from credit_pricer.index.cds_index import (
    adjust_to_index_quotes,
    constituents_from_spreads,
    index_intrinsic,
)
from credit_pricer.tranches.base_correlation import quote_from_base_correlations
from credit_pricer.tranches.tranche import TranchePricer

DATA = Path(__file__).resolve().parents[1] / "data"
HEADER = [
    "# SYNTHETIC - illustrative only. Not market data. Generated by scripts/make_synthetic_data.py",
    f"# valuation_date: {VALUATION_DATE.isoformat()}",
]

RATES = [
    ("deposit", "1M", 0.0430),
    ("deposit", "3M", 0.0425),
    ("deposit", "6M", 0.0415),
    ("swap", "1Y", 0.0398),
    ("swap", "2Y", 0.0378),
    ("swap", "3Y", 0.0367),
    ("swap", "5Y", 0.0362),
    ("swap", "7Y", 0.0366),
    ("swap", "10Y", 0.0375),
    ("swap", "15Y", 0.0388),
    ("swap", "20Y", 0.0392),
    ("swap", "30Y", 0.0384),
]

SINGLE_NAME_TENORS = [1, 2, 3, 5, 7, 10]
SINGLE_NAMES = {  # bp
    "ALPHA_IG_LOW": [18.0, 26.0, 36.0, 58.0, 72.0, 84.0],
    "BRAVO_IG_MID": [55.0, 74.0, 95.0, 132.0, 152.0, 166.0],
    "CHARLIE_HY": [240.0, 290.0, 335.0, 395.0, 418.0, 430.0],
}

INDEX_TENORS = [1, 3, 5, 7, 10]
INDEX_N = 125
INDEX_COUPON_BP = 100.0
INDEX_TERM_SHAPE = np.array([0.32, 0.62, 1.0, 1.22, 1.38])
INDEX_QUOTED_TENORS = [3, 5, 7, 10]
INDEX_BASIS_BP = [-1.5, -2.5, -3.0, -3.5]  # quoted minus intrinsic

TRANCHES = [  # attach, detach, running coupon (bp), generating base correlation at detach
    (0.00, 0.03, 500.0, 0.30),
    (0.03, 0.07, 500.0, 0.41),
    (0.07, 0.10, 100.0, 0.48),
    (0.10, 0.15, 100.0, 0.57),
    (0.15, 0.30, 100.0, 0.74),
]
TRANCHE_TENOR = 5
RECOVERY = 0.40


def _write(name: str, header: list[str], rows: list[list[object]]) -> None:
    path = DATA / name
    with path.open("w", newline="", encoding="utf-8") as fh:
        fh.write("\n".join(HEADER) + "\n")
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    print(f"wrote {path.relative_to(DATA.parent)}")


def main() -> None:
    DATA.mkdir(exist_ok=True)
    _write("synthetic_rates.csv", ["instrument", "tenor", "rate"], [list(r) for r in RATES])
    _write(
        "synthetic_single_name_spreads.csv",
        ["name", "recovery", *[f"{t}Y" for t in SINGLE_NAME_TENORS]],
        [[n, RECOVERY, *s] for n, s in SINGLE_NAMES.items()],
    )

    rng = np.random.default_rng(20261105)
    five_year = np.exp(rng.normal(np.log(60.0), 0.55, INDEX_N))
    five_year = np.clip(five_year, 15.0, 600.0)
    noise = rng.normal(0.0, 0.03, (INDEX_N, len(INDEX_TENORS)))
    shape = INDEX_TERM_SHAPE * (1.0 + noise)
    shape[:, INDEX_TENORS.index(5)] = 1.0
    shape = np.maximum.accumulate(shape, axis=1)  # upward-sloping curves
    spreads_bp = np.round(five_year[:, None] * shape, 2)
    names = [f"SYN{i + 1:03d}" for i in range(INDEX_N)]
    _write(
        "synthetic_index_constituents.csv",
        ["name", "recovery", *[f"{t}Y" for t in INDEX_TENORS]],
        [[n, RECOVERY, *row] for n, row in zip(names, spreads_bp.tolist())],
    )

    discount = load_discount_curve(DATA)
    members = constituents_from_spreads(
        VALUATION_DATE, discount, INDEX_TENORS, spreads_bp * 1e-4, RECOVERY, names
    )
    coupon = INDEX_COUPON_BP * 1e-4
    quoted: list[float] = []
    rows: list[list[object]] = []
    for tenor, basis in zip(INDEX_QUOTED_TENORS, INDEX_BASIS_BP):
        intr = index_intrinsic(VALUATION_DATE, tenor, coupon, members, discount)
        q = round(intr.spread * 1e4 + basis, 2)
        quoted.append(q * 1e-4)
        rows.append([f"{tenor}Y", INDEX_COUPON_BP, q])
    _write("synthetic_index_quotes.csv", ["tenor", "coupon_bp", "quoted_spread_bp"], rows)

    # Tranches are priced on the index-adjusted constituent curves (market practice).
    adjusted = adjust_to_index_quotes(
        VALUATION_DATE, INDEX_QUOTED_TENORS, quoted, coupon, members, discount
    )
    pricer = TranchePricer(
        VALUATION_DATE,
        TRANCHE_TENOR,
        [c.curve for c in adjusted.constituents],
        discount,
        RECOVERY,
    )
    rows = []
    rho_prev = 0.0
    for attach, detach, cpn_bp, rho in TRANCHES:
        tq = quote_from_base_correlations(pricer, attach, detach, rho_prev, rho, cpn_bp * 1e-4)
        rows.append(
            [f"{TRANCHE_TENOR}Y", round(attach * 100, 6), round(detach * 100, 6), cpn_bp,
             round(tq.upfront * 100, 6), rho]
        )
        rho_prev = rho
    _write(
        "synthetic_tranche_quotes.csv",
        ["tenor", "attach_pct", "detach_pct", "coupon_bp", "upfront_pct",
         "generating_base_correlation"],
        rows,
    )


if __name__ == "__main__":
    main()
