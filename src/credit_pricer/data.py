"""Loaders for the synthetic data sets shipped in the repository's ``data/`` folder.

Every file is SYNTHETIC and illustrative only: it is generated by
``scripts/make_synthetic_data.py`` and is not market data.
"""

from __future__ import annotations

import csv
import datetime as dt
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from numpy.typing import NDArray

from credit_pricer.curves.discount import (
    DepositQuote,
    DiscountCurve,
    SwapQuote,
    bootstrap_discount_curve,
)
from credit_pricer.tranches.base_correlation import TrancheQuote

VALUATION_DATE = dt.date(2026, 11, 5)
_PACKAGED = Path(__file__).resolve().parent / "_data"  # wheel install
_CHECKOUT = Path(__file__).resolve().parents[2] / "data"  # source checkout / editable
DEFAULT_DATA_DIR = _PACKAGED if _PACKAGED.is_dir() else _CHECKOUT


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as fh:
        lines = [ln for ln in fh if ln.strip() and not ln.startswith("#")]
    return list(csv.DictReader(lines))


def _dir(data_dir: Path | None) -> Path:
    d = DEFAULT_DATA_DIR if data_dir is None else Path(data_dir)
    if not d.is_dir():
        raise FileNotFoundError(f"data directory not found: {d}")
    return d


def load_rate_quotes(data_dir: Path | None = None) -> tuple[list[DepositQuote], list[SwapQuote]]:
    """Synthetic deposit and swap quotes."""
    deposits: list[DepositQuote] = []
    swaps: list[SwapQuote] = []
    for r in _rows(_dir(data_dir) / "synthetic_rates.csv"):
        tenor, rate = r["tenor"], float(r["rate"])
        if r["instrument"] == "deposit":
            deposits.append(DepositQuote(int(tenor.rstrip("M")), rate))
        elif r["instrument"] == "swap":
            swaps.append(SwapQuote(int(tenor.rstrip("Y")), rate))
        else:
            raise ValueError(f"unknown instrument {r['instrument']!r}")
    return deposits, swaps


def load_discount_curve(data_dir: Path | None = None) -> DiscountCurve:
    """Discount curve bootstrapped from the synthetic rate quotes."""
    deposits, swaps = load_rate_quotes(data_dir)
    return bootstrap_discount_curve(VALUATION_DATE, deposits, swaps)


@dataclass(frozen=True)
class SpreadCurveQuotes:
    """Par spread quotes (decimals) by tenor in years."""

    name: str
    tenors: list[int]
    spreads: list[float]
    recovery: float


def load_single_names(data_dir: Path | None = None) -> dict[str, SpreadCurveQuotes]:
    """Synthetic single-name CDS par spread curves (quoted in bp in the file)."""
    rows = _rows(_dir(data_dir) / "synthetic_single_name_spreads.csv")
    tenor_cols = [c for c in rows[0] if c.endswith("Y")]
    tenors = [int(c[:-1]) for c in tenor_cols]
    return {
        r["name"]: SpreadCurveQuotes(
            r["name"], tenors, [float(r[c]) * 1e-4 for c in tenor_cols], float(r["recovery"])
        )
        for r in rows
    }


@dataclass(frozen=True)
class IndexData:
    """Synthetic 125-name index: constituent spreads and quoted index spreads."""

    tenors: list[int]
    names: list[str]
    spreads: NDArray[np.float64]  # shape (n_names, n_tenors), decimals
    recovery: float
    coupon: float
    quoted_tenors: list[int]
    quoted_spreads: list[float]


def load_index(data_dir: Path | None = None) -> IndexData:
    """Constituent par spread curves and index quotes."""
    d = _dir(data_dir)
    rows = _rows(d / "synthetic_index_constituents.csv")
    tenor_cols = [c for c in rows[0] if c.endswith("Y")]
    spreads = np.array([[float(r[c]) * 1e-4 for c in tenor_cols] for r in rows])
    quotes = _rows(d / "synthetic_index_quotes.csv")
    return IndexData(
        tenors=[int(c[:-1]) for c in tenor_cols],
        names=[r["name"] for r in rows],
        spreads=spreads,
        recovery=float(rows[0]["recovery"]),
        coupon=float(quotes[0]["coupon_bp"]) * 1e-4,
        quoted_tenors=[int(q["tenor"].rstrip("Y")) for q in quotes],
        quoted_spreads=[float(q["quoted_spread_bp"]) * 1e-4 for q in quotes],
    )


@dataclass(frozen=True)
class TrancheData:
    """Synthetic 5y tranche quotes and the base correlations used to generate them."""

    tenor: int
    quotes: list[TrancheQuote]
    generating_correlations: list[float]


def load_tranche_quotes(data_dir: Path | None = None) -> TrancheData:
    """Upfront + running tranche quotes on the synthetic index pool."""
    rows = _rows(_dir(data_dir) / "synthetic_tranche_quotes.csv")
    quotes = [
        TrancheQuote(
            float(r["attach_pct"]) / 100.0,
            float(r["detach_pct"]) / 100.0,
            float(r["upfront_pct"]) / 100.0,
            float(r["coupon_bp"]) * 1e-4,
        )
        for r in rows
    ]
    tenors = {int(r["tenor"].rstrip("Y")) for r in rows}
    if len(tenors) != 1:
        raise ValueError("expected a single tranche maturity")
    return TrancheData(
        tenor=tenors.pop(),
        quotes=quotes,
        generating_correlations=[float(r["generating_base_correlation"]) for r in rows],
    )
